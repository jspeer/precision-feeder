#!/usr/bin/env python3
"""Write web/src/tz_zones.js: every IANA zone name and the POSIX TZ string ESPHome would compile for it.

The feeder takes a POSIX string (the Timezone entity), and a browser has no way to turn a zone name into one, so the
web app carries this table: the setup wizard and the Configuration page offer zone names and send the string. It is
the same extraction ESPHome does at build time (esphome.components.time), so a zone chosen in the app behaves exactly
as `timezone: <zone>` in the YAML. Run it with ESPHome's Python after a tzdata update, then tools/build_web.py:

    .venv/bin/python tools/gen_tz_zones.py

Part of the Precision Feeder ESPHome firmware (public domain, The Unlicense).
Designed and written with the assistance of an AI (Anthropic's Claude);
reviewed by a human, but it may still contain mistakes.
"""

import json
import pathlib
import zoneinfo

from esphome.components.time import _extract_tz_string, _load_tzdata

OUT = pathlib.Path(__file__).resolve().parent.parent / "web" / "src" / "tz_zones.js"


def main():
    rules: list[str] = []
    zones: list[str] = []
    for zone in sorted(zoneinfo.available_timezones()):
        # Only Area/Location names: the old aliases (EST, US/Eastern, Etc/GMT+5, ...) only add noise to a picker.
        if "/" not in zone or zone.startswith(("Etc/", "SystemV/", "US/", "posix/", "right/")):
            continue
        data = _load_tzdata(zone)
        text = _extract_tz_string(data) if data else None
        if not text:
            continue
        if text not in rules:
            rules.append(text)
        zones.append(f"{zone}={rules.index(text)}")
    OUT.write_text(
        "// Time zones (2.0.0 N6). GENERATED by tools/gen_tz_zones.py from the IANA database ESPHome uses: each zone\n"
        "// name and the POSIX TZ string ESPHome would compile for it. Do not edit by hand.\n"
        "//\n"
        "// Part of the Precision Feeder ESPHome firmware (public domain, The Unlicense).\n"
        "// Designed and written with the assistance of an AI (Anthropic's Claude);\n"
        "// reviewed by a human, but it may still contain mistakes.\n\n"
        f"const TZ_RULES = {json.dumps(rules, separators=(',', ':'))};\n"
        f"const TZ_ZONES = {json.dumps('|'.join(zones))};\n\n"
        "/** Every zone name, sorted, with its POSIX string: [[name, posix], ...]. */\n"
        "function tzZones() {\n"
        "  return TZ_ZONES.split('|').map(z => { const [n, i] = z.split('='); return [n, TZ_RULES[+i]]; });\n"
        "}\n\n"
        "/** The POSIX string for a zone name, or '' for a name not in the table. */\n"
        "function tzPosix(zone) {\n"
        "  const z = tzZones().find(([n]) => n === zone);\n"
        "  return z ? z[1] : '';\n"
        "}\n\n"
        "/** The zone names whose string is `posix` (several zones share one). */\n"
        "function tzNamesFor(posix) { return tzZones().filter(([, p]) => p === posix).map(([n]) => n); }\n"
    )
    print(f"{OUT.relative_to(OUT.parents[2])}: {len(zones)} zones, {len(rules)} rules")


if __name__ == "__main__":
    main()
