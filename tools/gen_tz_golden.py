#!/usr/bin/env python3
"""Write tests/tz_golden.h: every distinct POSIX TZ string in the IANA database, with the
fields ESPHome's reference parser (aioesphomeapi.posix_tz) gives it.

tests/test_core.cpp checks that the device's own parser (components/precision_feeder/tz_rules.h)
gives the same fields, and tests/test_consistency.py re-checks the table against the reference
when aioesphomeapi is installed. Run it with ESPHome's Python after a tzdata update:

    .venv/bin/python tools/gen_tz_golden.py

Part of the Precision Feeder ESPHome firmware (MIT licence, see LICENSE).
Designed and written with the assistance of an AI (Anthropic's Claude);
reviewed by a human, but it may still contain mistakes.
"""

import pathlib
import zoneinfo

from aioesphomeapi.posix_tz import parse_posix_tz
from esphome.components.time import _extract_tz_string, _load_tzdata

OUT = pathlib.Path(__file__).resolve().parent.parent / "tests" / "tz_golden.h"


def rule(r):
    return f"{{{r.time_seconds}, {r.day}, {int(r.type)}, {r.month}, {r.week}, {r.day_of_week}}}"


def main():
    first_zone = {}
    for zone in sorted(zoneinfo.available_timezones()):
        data = _load_tzdata(zone)
        text = _extract_tz_string(data) if data else None
        if text and text not in first_zone:
            first_zone[text] = zone
    lines = [
        "// Generated by tools/gen_tz_golden.py: every distinct POSIX TZ string in the IANA database and the fields",
        "// ESPHome's reference parser (aioesphomeapi.posix_tz) gives it. Do not edit by hand.",
        "//",
        "// Part of the Precision Feeder ESPHome firmware (MIT licence, see LICENSE).",
        "// Designed and written with the assistance of an AI (Anthropic's Claude);",
        "// reviewed by a human, but it may still contain mistakes.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "struct TzGoldenRule {",
        "  int32_t time_s;",
        "  int day, type, month, week, day_of_week;",
        "};",
        "struct TzGolden {",
        "  const char *text;",
        "  int32_t std_offset_s, dst_offset_s;",
        "  TzGoldenRule start, end;",
        "};",
        "",
        "static const TzGolden TZ_GOLDEN[] = {",
    ]
    for text, zone in first_zone.items():
        p = parse_posix_tz(text)
        lines.append(
            f'    {{"{text}", {p.std_offset_seconds}, {p.dst_offset_seconds}, {rule(p.dst_start)}, '
            f"{rule(p.dst_end)}}},  // {zone}"
        )
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: {len(first_zone)} timezones")


if __name__ == "__main__":
    main()
