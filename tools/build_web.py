#!/usr/bin/env python3
"""Build the web app: join web/src/ into the two files the firmware embeds (web/dist/app.js and app.css).

The app is plain JavaScript and CSS with no dependencies and no bundler. The sources are ordinary scripts that
share one module scope, joined in the order of SOURCES below (later files use what earlier ones define). ESPHome
gzips the result into the firmware (packages/web_server.yaml: js_include, css_include).

    python3 tools/build_web.py           build web/dist/
    python3 tools/build_web.py --check   fail if web/dist/ is not what web/src/ builds (tools/check.sh runs this)

web/dist/ is committed, so building the firmware needs nothing but ESPHome. Change web/src/, then run this.

Part of the Precision Feeder ESPHome firmware (public domain, The Unlicense).
Designed and written with the assistance of an AI (Anthropic's Claude);
reviewed by a human, but it may still contain mistakes.
"""

from __future__ import annotations

import gzip
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "src"
DIST = ROOT / "web" / "dist"

# Order matters: each file may use what the files before it define.
SOURCES = [
    "entities.js",   # every entity the app uses, by name (the UI contract)
    "parse.js",      # the device's text formats (pure; tested by tests/test_web.mjs)
    "store.js",      # the /events connection and the entity store
    "api.js",        # writes, one at a time, and waiting for the device's echo
    "ui.js",         # DOM helpers, icons, dialogs, toasts, form controls
    "banners.js",    # the warning banner
    "pages/dashboard.js",
    "pages/schedule.js",
    "pages/diagnostics.js",
    "app.js",        # the shell: header, tabs, routing; starts everything
]
STYLES = ["app.css"]

# The gzipped size the firmware carries; the plan's budget is about 60 KB for both files together.
BUDGET_GZ = 60 * 1024

HEADER = """\
// Precision Feeder web app. GENERATED by tools/build_web.py from web/src/: edit those files, not this one.
//
// Part of the Precision Feeder ESPHome firmware (public domain, The Unlicense).
// Designed and written with the assistance of an AI (Anthropic's Claude);
// reviewed by a human, but it may still contain mistakes.
"""
CSS_HEADER = """\
/* Precision Feeder web app. GENERATED by tools/build_web.py from web/src/: edit those files, not this one.

   Part of the Precision Feeder ESPHome firmware (public domain, The Unlicense).
   Designed and written with the assistance of an AI (Anthropic's Claude);
   reviewed by a human, but it may still contain mistakes. */
"""


def build() -> dict[str, str]:
    js = [HEADER]
    for name in SOURCES:
        js.append(f"\n// ---- {name} ----\n")
        js.append((SRC / name).read_text())
    css = [CSS_HEADER]
    for name in STYLES:
        css.append((SRC / name).read_text())
    return {"app.js": "".join(js), "app.css": "".join(css)}


def main() -> int:
    check = "--check" in sys.argv[1:]
    out = build()
    stale = [name for name, text in out.items() if not (DIST / name).exists() or (DIST / name).read_text() != text]
    gz = sum(len(gzip.compress(text.encode())) for text in out.values())
    if check:
        if stale:
            print(f"web/dist is out of date ({', '.join(stale)}): run python3 tools/build_web.py")
            return 1
    else:
        DIST.mkdir(parents=True, exist_ok=True)
        for name, text in out.items():
            (DIST / name).write_text(text)
    print(f"web app: {sum(len(t) for t in out.values()) // 1024} KB, {gz // 1024} KB gzipped "
          f"(budget {BUDGET_GZ // 1024} KB)")
    if gz > BUDGET_GZ:
        print("over the size budget")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
